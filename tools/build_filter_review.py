"""Present observed NES filter tails without processing the listening audio."""
import argparse
from html import escape
import json
from pathlib import Path
import numpy as np

from tools.audit_nes_filter import bound
from tools.benchmark_report import sha


def publish(audit, capture, listening, out):
    result=bound(audit)
    receipt=bound(capture/'report.json')
    audio=bound(listening/'report.json')
    if result['sources'].get(str(capture/'report.json'))!=sha(capture/'report.json'):
        raise ValueError('Different filter capture')
    example=max((r for r in result['observations'] if r['constant_input']),
                key=lambda r:r['output_ac_rms'])
    timeline=json.loads((capture/'timeline.json').read_text())
    row=timeline[example['source_frame']-1]
    raw=np.fromfile(receipt['traces']['samples'],dtype='<i4').reshape(-1,2)
    values=raw[row['start_sample']:row['end_sample']]
    if not np.all(values[:,0]==example['input_min']): raise ValueError('Example changed')
    # Plot every output sample. Fixed ±1200 output-unit scale, not an audio gain.
    if np.max(np.abs(values[:,1]))>1200: raise ValueError('Plot would clip')
    points=' '.join(f'{50+800*i/(len(values)-1):.3f},{170-float(v)/10:.3f}'
                    for i,v in enumerate(values[:,1]))
    svg=f'''<svg viewBox="0 0 920 350" role="img" aria-label="Frame1826: constant zero filter input, decaying output">
<path d="M50 50V290H850M50 170H850" fill="none" stroke="#889"/>
<text x="8" y="50">1200</text><text x="20" y="175">0</text><text x="0" y="290">−1200</text>
<polyline points="{points}" fill="none" stroke="#6df" stroke-width="2"/>
<path d="M50 170H850" stroke="#fb8" stroke-width="2" stroke-dasharray="8 5"/>
<text x="50" y="320">0ms</text><text x="750" y="320">{len(values)/48:.3f}ms</text>
<text x="90" y="30">Blue: delivered mono PCM units · dashed: pre-filter input = 0</text></svg>'''
    dynamic=[r for r in result['observations'] if not r['constant_input']]
    if any(r['source_frame']!=r['publication_frame'] or
           r['receipt_callback']!=r['source_frame']+1 for r in dynamic):
        raise ValueError('Dynamic callback boundary explanation no longer holds')
    rows=''.join('<tr>'+''.join('<td>'+str(r[k])+'</td>' for k in
        ('source_frame','packet','publication_frame','receipt_callback'))+'</tr>' for r in dynamic)
    page=f'''<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>RCR · filter tail versus missing note</title><style>body{{background:#101821;color:#eef;font:17px system-ui;max-width:1100px;margin:auto;padding:24px}}a{{color:#9df}}svg{{width:100%;fill:#eef}}td,th{{padding:9px;border:1px solid #567}}.open{{color:#ffd68b}}</style>
<h1>Filter tail versus missing note</h1>
<p>September18 · ROM071c89e unchanged; no hardware restart or inputs. <a href="report.json">Bound evidence manifest</a>.</p>
<p>The 257 previously flagged NES-active audio callbacks split into <strong>245 constant-input filter tails and12 changing-input callbacks</strong>. Every changing-input callback is one of the packet/audio-boundary cases found by the DSP trace. None of these observations demonstrates a dropped note.</p>
<h2>Actual measured filter behavior, not a fitted decay curve</h2>
<p>New observer reproduces the complete reference timeline, final RAM and WAV byte-for-byte. All7,144,636 mono filter outputs match both delivered stereo channels. An independent integer recurrence reconstructs every sample and validates the starting state of all8,946 filter blocks, using recorded coefficients. No filter bypass, offset search, gain changes or new ROM behavior.</p>
<h3>Largest constant-input discrepancy: source frame{example['source_frame']}</h3>{svg}
<p>All{len(values)} pre-filter samples are exactly0. Output moves from{example['output_first']} to{example['output_last']}, with AC RMS{example['output_ac_rms']:.3f}. This within-callback variation is generated by filter memory. Every sample is plotted; the audio remains untouched. This was selected as the strongest constant-input example, not a representative quality score.</p>
<p><a href="../{escape(listening.name)}/">Listen to native-rate NES/SNES context, frames1810–1840</a>.</p>
<h2>The12 changing-input cases</h2><table><tr><th>NES source frame</th><th>Packet</th><th>Publication label</th><th>Actual receipt callback</th></tr>{rows}</table>
<p>Each packet arrives after its labeled callback ended. Across all256 gap contexts, actual receipt-to-first-nonzero intervals were336–676 SPC cycles (about0.33–0.66ms nominal). <a href="../triangle-game-dsp-review-964/">Exact DSP timing audit and all256 gap contexts</a>.</p>
<p>There are256 gap contexts but257 active reference callbacks: one context includes both a filter-tail callback and a changing-input callback. All244 contexts previously unexplained by the callback boundary have constant-input reference activity.</p>
<h2>Still open</h2><p class="open">Filter tails are real parts of the reference sound; this does not certify the SNES cutoff/analog response or overall synthesis fidelity. The three147–151ms physical combat gaps and audible pops still require correlation with hardware gameplay. No speed, scrolling or release pass is implied.</p>
<p><a href="../triangle-game-followup-review-958/">Physical recording, unaltered audio, and exact-frame collages</a> · <a href="../triangle-game-filter-audit-966/report.json">Every callback measurement and source binding</a>.</p>
</html>'''
    out.mkdir(parents=True,exist_ok=False)
    (out/'index.html').write_text(page)
    sources={**result['sources'],**receipt['sources'],**audio['sources'],str(audit):sha(audit),
        str(listening/'report.json'):sha(listening/'report.json'),str(Path(__file__)):sha(Path(__file__))}
    (out/'report.json').write_text(json.dumps(dict(sources=sources,example=example,
        varying_input_callbacks=len(dynamic),page_sha256=sha(out/'index.html'),
        release_ready=False,physical_gaps_correlated=False),indent=2)+'\n')
    print(json.dumps(dict(source_bindings=len(sources),out=str(out))))


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    for name in ('audit','capture','listening','out'): p.add_argument('--'+name,type=Path,required=True)
    publish(**vars(p.parse_args()))
